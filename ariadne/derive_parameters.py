"""Turn drug_sources.yaml (IC50s, concentrations, citations) into drugs.yaml (model effects) with an audit trail.

  python derive_parameters.py [--gaba-weight 0.5]
"""
import argparse, os, yaml
HERE = os.path.dirname(os.path.abspath(__file__))


HIGH_EXPOSURE = False
CA_COOP = 2.6   # sourced: N-type Hill coefficient, Reid/Bekkers/Clements J Neurosci 1998;18:2849-2855


def derive(gaba_weight=None, high_exposure=False, nav_mode=None):
    global HIGH_EXPOSURE
    HIGH_EXPOSURE = high_exposure
    S = yaml.safe_load(open(os.path.join(HERE, "drug_sources.yaml")))
    MODE = S.pop("nav_mode"); MODE = nav_mode or MODE
    NAV_REF = S.pop("nav_ref"); GW = S.pop("gaba_weight") if gaba_weight is None else (S.pop("gaba_weight") and gaba_weight)
    if gaba_weight is not None: GW = gaba_weight
    out, rep = {}, []
    for name, d in S.items():
        free = None
        if d.get("free_conc_uM") is not None:
            free = d["free_conc_uM_high"] if (HIGH_EXPOSURE and d.get("free_conc_uM_high")) else d["free_conc_uM"]
        elif d.get("therapeutic_mg_per_L"):
            lo, hi = d["therapeutic_mg_per_L"]
            free = (lo + hi) / 2 / d["mw"] * 1000 * d["free_fraction"]
        occ = lambda ic50: free / (free + ic50)
        if MODE == "inactivated":
            nav = d["nav_vdb_block_override"] if d.get("nav_vdb_block_override") is not None else (
                  occ(d["nav_vdb_ic50_uM"]) if d.get("nav_vdb_ic50_uM") else d.get("nav_block_override", 0.0))
        else:
            nav = d["nav_block_override"] if d.get("nav_block_override") is not None else occ(d["nav_persistent_ic50_uM"])
        udb = occ(d["nav_udb10_ic50_uM"]) if d.get("nav_udb10_ic50_uM") else 0.0
        gaba = free / (free + d["gaba_ec50_uM"]) if d.get("gaba_ec50_uM") and free else 0.0
        x0 = (nav + GW * gaba) / NAV_REF + d["other_x0"]
        # Transmitter-release reduction: DERIVED from a measured calcium-current block where one exists,
        # because release is supralinear in presynaptic Ca (Hill coefficient 2.6 for N-type, Reid 1998).
        if d.get("ca_current_block") is not None:
            blk = float(d["ca_current_block_high"] if (HIGH_EXPOSURE and d.get("ca_current_block_high") is not None)
                        else d["ca_current_block"])
            release = 1.0 - (1.0 - blk) ** CA_COOP
            rel_note = f"Ca-current block {blk*100:.0f}% -> release reduction {release*100:.0f}% (cooperativity {CA_COOP}, sourced)"
        else:
            release = float(d["release_reduction"] or 0.0)
            rel_note = f"release reduction {release} (assumed)"
        out[name] = {"targets": d["targets"], "x0_effect": round(x0, 3), "coupling_effect": round(release, 3),
                     "nav_block_fraction": round(nav, 3), "nav_mode": MODE, "udb10_block_fraction": round(udb, 3), "gaba_fraction": round(gaba, 3),
                     "free_conc_uM": None if free is None else round(free, 1),
                     "rationale": f"{MODE} Na block {nav*100:.0f}%, GABA-A {gaba*100:.0f}% (free {free if free is None else round(free,1)} uM); other excitability {d['other_x0']} (assumed); {rel_note}",
                     "citation": "; ".join(d["sources"])}
        rep.append((name, free, nav, gaba, x0, release))
    return out, rep, (GW, MODE)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("--gaba-weight", type=float, default=None)
    ap.add_argument("--nav-mode", choices=["inactivated", "persistent"], default=None); a = ap.parse_args()
    out, rep, GW = derive(a.gaba_weight, nav_mode=a.nav_mode)
    hdr = ("# GENERATED by derive_parameters.py from drug_sources.yaml (gaba_weight=%s, nav_mode=%s). Edit drug_sources.yaml, not this file.\n" % GW)
    open(os.path.join(HERE, "drugs.yaml"), "w").write(hdr + yaml.safe_dump(out, sort_keys=False, width=220))
    print(f"{'drug':14s} free(uM)  Na-block  GABA   x0_effect  coupling")
    for n, f, nv, g, x, c in rep:
        print(f"{n:14s} {('-' if f is None else f'{f:7.1f}'):>8s}  {nv*100:6.1f}%  {g*100:4.0f}%  {x:8.2f}  {c:8.2f}")
